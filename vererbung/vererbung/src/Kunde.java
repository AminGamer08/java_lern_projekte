public class Kunde {
    //Attribute
    String name;
    int alter;
    String email;
    String telefonnummer;
    //Konstruktor
    public Kunde(String name, int alter, String email, String telefonnummer){
        this.name = name;
        this.alter = alter;
        this.email = email;
        this.telefonnummer = telefonnummer;
    }
}
